function buildPrompt(p) {
  const [abbr, name, cityList] = p;
  const n = cityList.split(',').length;
  return `你是一位中国人文地理与城市知识专家。请为「${name}」的每个城市生成用于「车牌记忆 App」的详细内容。

车牌字母与城市对应（字母:城市），共 ${n} 个：
${cityList}

为每个城市生成 6 个字段：
- l: 车牌字母（原样保留，如 "B"）
- city: 城市名（原样保留，不要改名）
- h: 人文历史，一句短语 10~20 字（如 "六朝古都·江南水乡"）
- s: 风景地标 3~4 个，用 " · " 分隔（如 "中山陵 · 夫子庙 · 明孝陵 · 玄武湖"）
- f: 美食特产 2~3 个，用 " · " 分隔（如 "盐水鸭 · 鸭血粉丝汤 · 小笼包"）
- tip: 记忆点，一句话谐音/联想帮助把「车牌字母+城市」绑定记忆（省会/首府 A 牌可写 "A=省会" 或更好记的联想，如 "浙A杭州=Alibaba在杭州"）
- desc: 城市简介 25~40 字，生动有画面感（如 "六朝古都，秦淮河畔的千年繁华，梧桐树影里藏着半部中国近代史"）

要求：内容真实准确、通俗易记、不编造离谱细节；自治州/盟等地名原样保留。

把结果写成如下 JSON（严格单行或标准 JSON 均可，只输出 JSON，不要任何解释文字）：
{"abbr":"${abbr}","name":"${name}","cities":[{"l":"...","city":"...","h":"...","s":"...","f":"...","tip":"...","desc":"..."}, ...]}

然后用你的 write 工具，把这段 JSON 原样写入文件：
${OUT}\\${abbr}.json

写入完成后，只回复一行：OK ${abbr} ${n}`;
}

